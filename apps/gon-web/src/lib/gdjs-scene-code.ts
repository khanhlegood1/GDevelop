/**
 * Apply-5 (27/10) — Sinh "scene generated code" cho GDJS Runtime theo QUY ƯỚC
 * CHÍNH THỨC của GDJS: gdjs["<mangledName>Code"] = { func, idToCallbackMap }
 * (xem RuntimeScene.setEventsGeneratedCodeFunction). libGD generate code này
 * khi export bằng GDevelop; GON sinh bằng generator tĩnh, data-driven từ
 * Module Graph đã lọc — vẫn tuân FE-10: không tự viết game code tự do, mọi
 * tham số người dùng được JSON.stringify (escape) vào template cố định.
 *
 * Hành vi template (mỗi frame):
 * - Nếu chuột trái vừa thả: với mỗi object node (GonNode*) chưa xem, nếu điểm
 *   chuột nằm trên AABB → gửi GonLearningEvents::objective_viewed + đổi màu
 *   object sang xanh (đã xem) qua TextObject::SetColor.
 * - Khi mọi node đã xem và chưa gửi checkpoint → gửi checkpoint_reached.
 */
import type { GdjsProjectData } from "./gdjs-launch";

export interface GdjsSceneNodeSpec {
  objectName: string;
  nodeId: string;
  title: string;
}

/** Lấy danh sách node-object từ project đã sinh (tên GonNode{i}). */
export function gdjsNodeSpecsFromProject(project: GdjsProjectData, nodeIds: Array<{ id?: unknown; title?: unknown }>): GdjsSceneNodeSpec[] {
  const layout = project.layouts[0];
  if (!layout) return [];
  const specs: GdjsSceneNodeSpec[] = [];
  const nodeObjects = layout.objects.filter((object) => /^GonNode\d+$/.test(object.name)).sort((a, b) => {
    return Number(a.name.slice("GonNode".length)) - Number(b.name.slice("GonNode".length));
  });
  nodeObjects.forEach((object, index) => {
    const source = nodeIds[index] ?? {};
    specs.push({
      objectName: object.name,
      nodeId: typeof source.id === "string" ? source.id : object.name,
      title: typeof source.title === "string" ? source.title : object.string,
    });
  });
  return specs;
}

/**
 * Sinh nguồn JS của module scene code (chuỗi — launcher chèn bằng script tag
 * cùng origin sau khi runtime load). Tất cả dữ liệu từ graph chỉ lọt vào dưới
 * dạng JSON.stringify.
 */
export function gdjsSceneCodeSource(specs: GdjsSceneNodeSpec[], options: { sceneName?: string } = {}): string {
  const sceneName = options.sceneName ?? "MainScene";
  const nodes = JSON.stringify(
    specs.map((spec) => ({ objectName: spec.objectName, nodeId: spec.nodeId, title: spec.title })),
  );
  return `// Generated by GON gdjsSceneCodeSource (Apply-5) — quy ước GDJS <mangledName>Code.
gdjs["${sceneName}Code"] = {
  idToCallbackMap: {},
  func: function (runtimeScene) {
    var NODES = ${nodes};
    var seenKey = "gon_node_seen_";
    var checkpointDoneKey = "gon_checkpoint_sent";
    var gonVars = runtimeScene.getVariables().get("GonState");
    var inputManager = runtimeScene.getGame().getInputManager();
    var mouseJustReleased = false;
    try {
      mouseJustReleased = inputManager.isMouseButtonReleased(0);
    } catch (e) {
      mouseJustReleased = false;
    }
    var mouseDown = false;
    try {
      mouseDown = inputManager.isMouseButtonPressed(0);
    } catch (e) {
      mouseDown = false;
    }
    if (!mouseJustReleased && !mouseDown) return;

    var mouseX = 0;
    var mouseY = 0;
    try {
      mouseX = inputManager.getMouseX();
      mouseY = inputManager.getMouseY();
    } catch (e) {
      return;
    }

    var allSeen = true;
    for (var i = 0; i < NODES.length; i++) {
      var node = NODES[i];
      var seen = !!gonVars.getChild(seenKey + i).getAsBoolean();
      if (!seen) {
        var objects = runtimeScene.getObjects(node.objectName);
        for (var j = 0; j < objects.length; j++) {
          var object = objects[j];
          if (gdjs.evtTools.gonLearningEvents.pointIsOnObject(object, mouseX, mouseY)) {
            seen = true;
            gonVars.getChild(seenKey + i).setBoolean(true);
            object.setString("\\u2705 " + object.getString());
            object.setColor("90;200;120");
            gdjs.evtTools.gonLearningEvents.sendGameEvent(
              "objective_viewed",
              JSON.stringify({ nodeId: node.nodeId, title: node.title, source: "gdjs_in_game" })
            );
            break;
          }
        }
      }
      if (!seen) allSeen = false;
    }

    if (allSeen && !gonVars.getChild(checkpointDoneKey).getAsBoolean()) {
      gonVars.getChild(checkpointDoneKey).setBoolean(true);
      gdjs.evtTools.gonLearningEvents.sendGameEvent(
        "checkpoint_reached",
        JSON.stringify({ checkpointId: "all_nodes_viewed", nodeCount: NODES.length, source: "gdjs_in_game" })
      );
    }
  },
};
`;
}
